-- HOTEL / RESORT DATABASE - STAGE 2
-- Complete recreation script for a group member's Oracle APEX schema.
-- Creates 10 tables, constraints, sample data, and 3 required views.
-- CREATE ROLE / GRANT is not included because APEX parsing schemas
-- commonly do not have database-level role administration privileges.

CREATE TABLE GUEST (
    Guest_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    First_name VARCHAR2(45) NOT NULL,
    Last_name VARCHAR2(45) NOT NULL,
    Phone VARCHAR2(45) NOT NULL,
    Email VARCHAR2(45) NOT NULL,
    Nationality VARCHAR2(45) NOT NULL,
    CONSTRAINT pk_guest PRIMARY KEY (Guest_id),
    CONSTRAINT uq_guest_email UNIQUE (Email)
);

CREATE TABLE DEPARTMENT (
    Department_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Department_name VARCHAR2(45) NOT NULL,
    Location VARCHAR2(45) NOT NULL,
    CONSTRAINT pk_department PRIMARY KEY (Department_id),
    CONSTRAINT uq_department_name UNIQUE (Department_name)
);

CREATE TABLE EMPLOYEE (
    Employee_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Department_id NUMBER NOT NULL,
    First_name VARCHAR2(45) NOT NULL,
    Last_name VARCHAR2(45) NOT NULL,
    Position VARCHAR2(45) NOT NULL,
    Salary NUMBER(10,2) NOT NULL,
    Phone VARCHAR2(45),
    CONSTRAINT pk_employee PRIMARY KEY (Employee_id),
    CONSTRAINT fk_employee_department FOREIGN KEY (Department_id)
        REFERENCES DEPARTMENT(Department_id),
    CONSTRAINT chk_employee_salary CHECK (Salary >= 0)
);

CREATE TABLE ROOM_TYPE (
    Room_Type_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Type_name VARCHAR2(45) NOT NULL,
    Description VARCHAR2(45),
    Price_Per_Night NUMBER(10,2) NOT NULL,
    Capacity NUMBER NOT NULL,
    CONSTRAINT pk_room_type PRIMARY KEY (Room_Type_id),
    CONSTRAINT uq_room_type_name UNIQUE (Type_name),
    CONSTRAINT chk_room_type_price CHECK (Price_Per_Night > 0),
    CONSTRAINT chk_room_type_capacity CHECK (Capacity > 0)
);

CREATE TABLE ROOM (
    Room_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Room_number VARCHAR2(10) NOT NULL,
    Room_Type_id NUMBER NOT NULL,
    Floor_number NUMBER NOT NULL,
    Status VARCHAR2(20) NOT NULL,
    CONSTRAINT pk_room PRIMARY KEY (Room_id),
    CONSTRAINT uq_room_number UNIQUE (Room_number),
    CONSTRAINT fk_room_type FOREIGN KEY (Room_Type_id)
        REFERENCES ROOM_TYPE(Room_Type_id),
    CONSTRAINT chk_room_floor CHECK (Floor_number > 0)
);

CREATE TABLE RESERVATION (
    Reservation_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Guest_id NUMBER NOT NULL,
    Booking_Date DATE DEFAULT SYSDATE NOT NULL,
    Check_in DATE NOT NULL,
    Check_out DATE NOT NULL,
    Status VARCHAR2(45) NOT NULL,
    CONSTRAINT pk_reservation PRIMARY KEY (Reservation_id),
    CONSTRAINT fk_reservation_guest FOREIGN KEY (Guest_id)
        REFERENCES GUEST(Guest_id),
    CONSTRAINT chk_reservation_dates CHECK (Check_out > Check_in)
);

CREATE TABLE RESERVATION_ROOM (
    Reservation_id NUMBER NOT NULL,
    Room_id NUMBER NOT NULL,
    Nightly_Rate NUMBER(10,2) NOT NULL,
    CONSTRAINT pk_reservation_room PRIMARY KEY (Reservation_id, Room_id),
    CONSTRAINT fk_reservation_room_res FOREIGN KEY (Reservation_id)
        REFERENCES RESERVATION(Reservation_id) ON DELETE CASCADE,
    CONSTRAINT fk_reservation_room_room FOREIGN KEY (Room_id)
        REFERENCES ROOM(Room_id),
    CONSTRAINT chk_nightly_rate CHECK (Nightly_Rate > 0)
);

CREATE TABLE SERVICE (
    Service_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Service_Name VARCHAR2(45) NOT NULL,
    Description VARCHAR2(45),
    Price NUMBER(10,2) NOT NULL,
    CONSTRAINT pk_service PRIMARY KEY (Service_id),
    CONSTRAINT uq_service_name UNIQUE (Service_Name),
    CONSTRAINT chk_service_price CHECK (Price > 0)
);

CREATE TABLE RESERVATION_SERVICE (
    Reservation_id NUMBER NOT NULL,
    Service_id NUMBER NOT NULL,
    Quantity NUMBER NOT NULL,
    Service_date DATE NOT NULL,
    CONSTRAINT pk_reservation_service PRIMARY KEY (Reservation_id, Service_id),
    CONSTRAINT fk_reservation_service_res FOREIGN KEY (Reservation_id)
        REFERENCES RESERVATION(Reservation_id) ON DELETE CASCADE,
    CONSTRAINT fk_reservation_service_service FOREIGN KEY (Service_id)
        REFERENCES SERVICE(Service_id),
    CONSTRAINT chk_service_quantity CHECK (Quantity > 0)
);

CREATE TABLE PAYMENT (
    Payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    Payment_Date DATE NOT NULL,
    Amount NUMBER(10,2) NOT NULL,
    Payment_Method VARCHAR2(45) NOT NULL,
    Payment_Status VARCHAR2(45) NOT NULL,
    Reservation_id NUMBER NOT NULL,
    CONSTRAINT pk_payment PRIMARY KEY (Payment_id),
    CONSTRAINT uq_payment_reservation UNIQUE (Reservation_id),
    CONSTRAINT fk_payment_reservation FOREIGN KEY (Reservation_id)
        REFERENCES RESERVATION(Reservation_id),
    CONSTRAINT chk_payment_amount CHECK (Amount > 0)
);

