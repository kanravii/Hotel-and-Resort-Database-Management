CREATE OR REPLACE VIEW VW_RESERVATION_DETAILS AS
SELECT r.Reservation_id,
       g.First_name || ' ' || g.Last_name AS Guest_Name,
       r.Booking_Date, r.Check_in, r.Check_out, r.Status,
       rm.Room_number, rt.Type_name AS Room_Type, rr.Nightly_Rate
FROM RESERVATION r
JOIN GUEST g ON r.Guest_id = g.Guest_id
JOIN RESERVATION_ROOM rr ON r.Reservation_id = rr.Reservation_id
JOIN ROOM rm ON rr.Room_id = rm.Room_id
JOIN ROOM_TYPE rt ON rm.Room_Type_id = rt.Room_Type_id;

CREATE OR REPLACE VIEW VW_DEPARTMENT_EMPLOYEE_SUMMARY AS
SELECT d.Department_id, d.Department_name,
       COUNT(e.Employee_id) AS Employee_Count,
       ROUND(AVG(e.Salary),2) AS Average_Salary,
       SUM(e.Salary) AS Total_Salary
FROM DEPARTMENT d
LEFT JOIN EMPLOYEE e ON d.Department_id = e.Department_id
GROUP BY d.Department_id, d.Department_name;

CREATE OR REPLACE VIEW VW_TOP_ROOMS AS
SELECT Room_Number, Room_Type, Reservation_Count
FROM (
    SELECT rm.Room_number,
           rt.Type_name AS Room_Type,
           COUNT(rr.Reservation_id) AS Reservation_Count
    FROM ROOM rm
    JOIN ROOM_TYPE rt ON rm.Room_Type_id = rt.Room_Type_id
    JOIN RESERVATION_ROOM rr ON rm.Room_id = rr.Room_id
    GROUP BY rm.Room_number, rt.Type_name
    ORDER BY COUNT(rr.Reservation_id) DESC
)
WHERE ROWNUM <= 5;

